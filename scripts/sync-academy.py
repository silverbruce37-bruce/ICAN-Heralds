#!/usr/bin/env python3
"""Sync data/academy-<date>.json into js/academy-data.js.

The academy JSON holds the level-by-level background knowledge layers for one
edition. The site reads only js/academy-data.js, so every edition must pass
through this script. It also checks that each article really carries the four
learning layers (depth 1-4) that the LEARN level selector offers, and prints a
warning naming any article that is short a layer.

Usage:
    python3 scripts/sync-academy.py --date 2026-11-27
    python3 scripts/sync-academy.py            # latest data/academy-*.json
"""
import argparse
import glob
import json
import re
import sys

REQUIRED_DEPTHS = [1, 2, 3, 4]
ARTICLE_KEYS = ["cover", "featured", "news_1", "news_2", "news_3", "news_4"]


def load_academy(path):
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    raw = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", " ", raw)
    if not raw.strip().startswith("{"):
        start, end = raw.find("{"), raw.rfind("}")
        if start >= 0 and end > start:
            raw = raw[start:end + 1]
    return json.loads(raw)


def article_map(daily):
    mapping = {"cover": daily.get("cover_story", {}), "featured": daily.get("featured_news", {})}
    for i in range(1, 5):
        if i - 1 < len(daily.get("news_grid", [])):
            mapping[f"news_{i}"] = daily["news_grid"][i - 1]
    return mapping


def check_layers(key, layers):
    """Return the list of missing depths for one article."""
    have = set()
    for layer in layers:
        try:
            have.add(int(layer.get("depth")))
        except (TypeError, ValueError):
            continue
    return [d for d in REQUIRED_DEPTHS if d not in have]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", default="", help="edition date, e.g. 2026-11-27")
    args = parser.parse_args()

    if args.date:
        academy_file = f"data/academy-{args.date}.json"
    else:
        files = sorted(glob.glob("data/academy-*.json"))
        if not files:
            print("ERROR: no data/academy-*.json found", file=sys.stderr)
            return 1
        academy_file = files[-1]
    date = academy_file.split("academy-", 1)[1].rsplit(".json", 1)[0]

    academy = load_academy(academy_file)
    with open(f"data/daily-{date}.json", encoding="utf-8") as f:
        daily = json.load(f)

    js_data = {}
    short = []
    for key, art in article_map(daily).items():
        if key not in academy:
            short.append(f"{key}: missing article")
            continue
        layers = sorted(academy[key].get("layers", []), key=lambda l: int(l.get("depth", 0) or 0))
        js_data[key] = {
            "tag": art.get("tag", "News"),
            "tagClass": art.get("tag_class", "tag-economy"),
            "title_en": art.get("headline_en", ""),
            "title_kr": art.get("headline_kr", ""),
            "summary_en": art.get("subtitle_en", art.get("summary_en", art.get("lead_en", ""))),
            "summary_kr": art.get("subtitle_kr", art.get("summary_kr", art.get("lead_kr", ""))),
            "layers": layers,
        }
        tok = academy[key].get("tok")
        if isinstance(tok, dict) and tok.get("question_en"):
            js_data[key]["tok"] = tok
        missing = check_layers(key, layers)
        if missing:
            short.append(f"{key}: no L{', L'.join(str(m) for m in missing)}")

    content = f"// Auto-generated by scripts/sync-academy.py — {date}\n"
    content += "var academyData = " + json.dumps(js_data, ensure_ascii=False, indent=2) + ";\n"
    content += "var paulSuggestions = {};\n"
    for key in ARTICLE_KEYS:
        if key in js_data and key in academy and "suggestions_en" in academy[key]:
            content += (
                f'paulSuggestions["{key}"] = {{ en: '
                f'{json.dumps(academy[key]["suggestions_en"], ensure_ascii=False)}, kr: '
                f'{json.dumps(academy[key]["suggestions_kr"], ensure_ascii=False)} }};\n'
            )

    with open("js/academy-data.js", "w", encoding="utf-8") as f:
        f.write(content)

    print(f"  Synced {academy_file} → js/academy-data.js ({len(js_data)} articles)")
    if short:
        print("  WARNING: learning layers incomplete — " + "; ".join(short), file=sys.stderr)
        print("  WARNING: the LEARN level selector will show fewer than four levels for these articles.",
              file=sys.stderr)
        return 2
    print("  Layers OK: every article has L1-L4")
    return 0


if __name__ == "__main__":
    sys.exit(main())
